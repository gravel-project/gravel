var update = flag.Bool("update", false, "rewrite the golden files in testdata/")

// matrixGolden is the pinned answer of every procedure to every kind of caller.
const matrixGolden = "testdata/access_matrix.txt"

// matrixBodies are request bodies (Connect JSON) for the procedures whose input is checked before
// the caller would be, so the matrix shows who is admitted rather than what is malformed. A
// procedure missing here is sent {}.
var matrixBodies = map[string]string{}

// TestAccessMatrix calls every procedure of the hub's API as every kind of caller and compares the
// answers with testdata/access_matrix.txt: the access matrix of ADR-0027. A change to who may call
// what shows up as a diff of that file, which the pull request carries (go test -run
// TestAccessMatrix -update rewrites it). A procedure the file does not list fails the test, so a
// new one is a decision too.
//
// An answer is the Connect code, or "ok"; anything but unauthenticated and permission_denied
// means the caller was admitted and the call went on to fail or succeed on its own merits (the rig
// has no servers, so most admitted calls are not_found).
func TestAccessMatrix(t *testing.T) {
	r := newRig(t)
	ctx := context.Background()

	owner := r.user(t, "Owner", "1")
	if _, err := r.org.Claim(ctx, r.token, owner.ID); err != nil {
		t.Fatal(err)
	}
	mod := r.user(t, "Mod", "2")
	if _, err := r.ids.SetRole(ctx, mod.ID, "moderator", true, owner.ID); err != nil {
		t.Fatal(err)
	}
	member := r.user(t, "Member", "3")

	memberScopes := slices.Sorted(func(yield func(string) bool) {
		for s := range apps.MemberScopes {
			if !yield(s) {
				return
			}
		}
	})
	appScopes := slices.Sorted(func(yield func(string) bool) {
		for s := range apps.Scopes {
			if !yield(s) {
				return
			}
		}
	})

	// A session caller logs in afresh for every call, since Logout and RevokeSessions end the
	// session they are called with.
	type principal struct {
		name   string
		client func() *http.Client
	}
	fixed := func(c *http.Client) func() *http.Client { return func() *http.Client { return c } }
	session := func(id uuid.UUID) func() *http.Client {
		return func() *http.Client { return cookieClient(http.DefaultClient, r.login(t, id)) }
	}
	principals := []principal{
		{"anonymous", fixed(http.DefaultClient)},
		{"member", session(member.ID)},
		{"moderator", session(mod.ID)},
		{"owner", session(owner.ID)},
		{"member-token", fixed(memberClient(r.memberToken(t, member.ID, memberScopes, memberScopes...)))},
		{"moderator-token", fixed(memberClient(r.memberToken(t, mod.ID, memberScopes, memberScopes...)))},
		{"owner-token", fixed(memberClient(r.memberToken(t, owner.ID, memberScopes, memberScopes...)))},
		{"owner-token-unscoped", fixed(memberClient(r.memberToken(t, owner.ID, memberScopes)))},
		{"app", fixed(bearerClient(http.DefaultClient, r.bearer(t, "app-none")))},
		{"app-host", fixed(bearerClient(http.DefaultClient, r.bearer(t, "app-host", "host:test:write")))},
	}
	for _, s := range appScopes {
		principals = append(principals, principal{"app+" + s, fixed(bearerClient(http.DefaultClient, r.bearer(t, "app-"+s, s)))})
	}
	principals = append(principals, principal{"app+all", fixed(bearerClient(http.DefaultClient, r.bearer(t, "app-all", appScopes...)))})

	procs := hubProcedures(t)
	var b strings.Builder
	b.WriteString("# The hub's access matrix (ADR-0027): every procedure's answer to every kind of caller.\n")
	b.WriteString("# Generated by TestAccessMatrix; rewrite with: go test ./internal/api -run TestAccessMatrix -update\n")
	b.WriteString("# ok = admitted and answered; any other code but unauthenticated and permission_denied means admitted too.\n")
	b.WriteString("# Principals:")
	for _, p := range principals {
		b.WriteString(" " + p.name)
	}
	b.WriteString("\n")
	for _, proc := range procs {
		fmt.Fprintf(&b, "\n%s\n", proc.path)
		for _, p := range principals {
			fmt.Fprintf(&b, "  %-30s %s\n", p.name, call(t, r.srv.URL, p.client(), proc))
		}
	}
	got := b.String()

	if *update {
		if err := os.WriteFile(filepath.FromSlash(matrixGolden), []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.FromSlash(matrixGolden))
	if err != nil {
		t.Fatalf("%v (go test ./internal/api -run TestAccessMatrix -update writes it)", err)
	}
	if got != string(want) {
		t.Errorf("the access matrix changed; if that is intended, rewrite %s with -update and commit the diff:\n%s", matrixGolden, lineDiff(string(want), got))
	}
}

type procedure struct {
	path      string
	streaming bool
}

// hubProcedures is every procedure in the gravel.hub.v1 package, sorted.
func hubProcedures(t *testing.T) []procedure {
	t.Helper()
	var out []procedure
	protoregistry.GlobalFiles.RangeFilesByPackage("gravel.hub.v1", func(fd protoreflect.FileDescriptor) bool {
		for i := range fd.Services().Len() {
			svc := fd.Services().Get(i)
			for j := range svc.Methods().Len() {
				m := svc.Methods().Get(j)
				if m.IsStreamingClient() {
					t.Fatalf("%s: client streaming is not supported by the matrix", m.FullName())
				}
				out = append(out, procedure{path: "/" + string(svc.FullName()) + "/" + string(m.Name()), streaming: m.IsStreamingServer()})
			}
		}
		return true
	})
	slices.SortFunc(out, func(a, b procedure) int { return strings.Compare(a.path, b.path) })
	if len(out) == 0 {
		t.Fatal("no procedures registered")
	}
	return out
}

// call sends one request with the Connect protocol over JSON and returns its code, or "ok".
func call(t *testing.T, base string, c *http.Client, p procedure) string {
	t.Helper()
	body := matrixBodies[p.path]
	if body == "" {
		body = "{}"
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	var req *http.Request
	var err error
	if p.streaming {
		var env bytes.Buffer
		env.WriteByte(0)
		_ = binary.Write(&env, binary.BigEndian, uint32(len(body)))
		env.WriteString(body)
		req, err = http.NewRequestWithContext(ctx, http.MethodPost, base+p.path, &env)
		if err == nil {
			req.Header.Set("Content-Type", "application/connect+json")
		}
	} else {
		req, err = http.NewRequestWithContext(ctx, http.MethodPost, base+p.path, strings.NewReader(body))
		if err == nil {
			req.Header.Set("Content-Type", "application/json")
		}
	}
	if err != nil {
		t.Fatal(err)
	}
	resp, err := c.Do(req)
	if err != nil {
		t.Fatalf("%s: %v", p.path, err)
	}
	defer resp.Body.Close()
	if !p.streaming {
		if resp.StatusCode == http.StatusOK {
			return "ok"
		}
		var e struct{ Code string }
		if err := json.NewDecoder(resp.Body).Decode(&e); err != nil || e.Code == "" {
			return fmt.Sprintf("http_%d", resp.StatusCode)
		}
		return e.Code
	}
	if resp.StatusCode != http.StatusOK {
		return fmt.Sprintf("http_%d", resp.StatusCode)
	}
	// The first envelope says it: a message is an admitted stream; the end-of-stream envelope
	// carries the error, if any. A stream that sends nothing in time was admitted and is waiting.
	var head [5]byte
	if _, err := io.ReadFull(resp.Body, head[:]); err != nil {
		if errors.Is(err, context.DeadlineExceeded) || ctx.Err() != nil {
			return "ok"
		}
		t.Fatalf("%s: %v", p.path, err)
	}
	if head[0]&0x02 == 0 {
		return "ok"
	}
	msg := make([]byte, binary.BigEndian.Uint32(head[1:]))
	if _, err := io.ReadFull(resp.Body, msg); err != nil {
		t.Fatalf("%s: %v", p.path, err)
	}
	var end struct{ Error *struct{ Code string } }
	if err := json.Unmarshal(msg, &end); err != nil {
		t.Fatalf("%s: %v", p.path, err)
	}
	if end.Error == nil {
		return "ok"
	}
	return end.Error.Code
}

// lineDiff lists the lines of want missing from got (-) and of got missing from want (+), with
// the procedure each sits under.
func lineDiff(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	in := func(lines []string) map[string]bool {
		m := map[string]bool{}
		proc := ""
		for _, l := range lines {
			if strings.HasPrefix(l, "/") {
				proc = l
			}
			m[proc+" | "+l] = true
		}
		return m
	}
	wm, gm := in(w), in(g)
	var b strings.Builder
	for _, set := range []struct {
		sign  string
		lines []string
		other map[string]bool
	}{{"-", w, gm}, {"+", g, wm}} {
		proc := ""
		for _, l := range set.lines {
			if strings.HasPrefix(l, "/") {
				proc = l
			}
			if !set.other[proc+" | "+l] {
				fmt.Fprintf(&b, "%s %s | %s\n", set.sign, proc, strings.TrimSpace(l))
			}
		}
	}
	return b.String()
}

